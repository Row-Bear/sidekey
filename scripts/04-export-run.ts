import "dotenv/config";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { CORE_STEP_COUNT, loadResults, requireEnv, STEPS, type StepResult } from "@poc/core";

const RESULTS_PATH = new URL("../demo-run.json", import.meta.url);
const OUT_PATH = fileURLToPath(new URL("../docs/recorded-run.md", import.meta.url));
const EXPLORER = "https://stellar.expert/explorer/testnet";

const xlm = (stroops: string) => (Number(BigInt(stroops)) / 1e7).toLocaleString("en-US", { maximumFractionDigits: 4 });

function row(result: StepResult): string {
  const outcome = result.outcome === "success" ? "Succeeded" : "Rejected by policy";
  const evidence = result.txHash
    ? `[${result.txHash.slice(0, 12)}…](${result.explorerUrl})`
    : `Not submitted: ${result.error ?? "rejected"}`;
  const balances = `${xlm(result.before.accountXlm)} → ${xlm(result.after.accountXlm)} / ${xlm(result.before.deposited)} → ${xlm(result.after.deposited)}`;
  return `| ${result.step} | ${STEPS[result.step - 1].name} | ${result.signer} | ${outcome} | ${evidence} | ${balances} |`;
}

const results = Object.values(loadResults(RESULTS_PATH)).sort((a, b) => a.step - b.step);
// Every core step must be present; the optional expiry steps are included when they were run.
const complete = Array.from({ length: CORE_STEP_COUNT }, (_, i) => results.some((r) => r.step === i + 1)).every(Boolean);
if (!complete || results.some((r) => !r.asExpected)) {
  throw new Error("demo-run.json is not a complete run where every step behaved as expected; refusing to export it.");
}

const smartAccount = requireEnv("SMART_ACCOUNT_ID");
const lines = [
  "# Recorded testnet run",
  "",
  "Generated by `npm run export:run` from `demo-run.json`. Use it as a fallback if live testnet is unavailable.",
  "",
  `- Smart account: [${smartAccount}](${EXPLORER}/contract/${smartAccount})`,
  `- Master signer: [${requireEnv("MASTER_PUBLIC")}](${EXPLORER}/account/${requireEnv("MASTER_PUBLIC")})`,
  `- Delegate signer: [${requireEnv("DELEGATE_PUBLIC")}](${EXPLORER}/account/${requireEnv("DELEGATE_PUBLIC")})`,
  `- Fee sponsor: [${requireEnv("SPONSOR_PUBLIC")}](${EXPLORER}/account/${requireEnv("SPONSOR_PUBLIC")})`,
  `- Yield simulator: [${requireEnv("YIELD_SIM_CONTRACT_ID")}](${EXPLORER}/contract/${requireEnv("YIELD_SIM_CONTRACT_ID")})`,
  `- Recorded: ${results[results.length - 1].at}`,
  "",
  "Balances are in XLM: smart account balance / amount deposited in the simulator, before → after each step.",
  "",
  "| # | Step | Signer | Outcome | Evidence | Balances |",
  "|---|------|--------|---------|----------|----------|",
  ...results.map(row),
  "",
  "Steps 6 and 9 are rejected during the enforcing simulation, before submission, so they have no transaction.",
  "The host reports `Auth/InvalidAction`; the diagnostics show the account's `__check_auth` returned",
  "`NotAllowed (#3)` for step 6 (the policy) and `SignerExpired (#5)` for step 9 (the delegate's expiry).",
  "",
];
writeFileSync(OUT_PATH, lines.join("\n"));
console.log(`Wrote ${OUT_PATH}`);
